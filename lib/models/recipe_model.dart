class RecipeIngredient {
  final String name;
  final String quantity;
  final String? imageUrl;

  const RecipeIngredient({
    required this.name,
    required this.quantity,
    this.imageUrl,
  });
}

class RecipeStep {
  final int stepNumber;
  final String title;
  final String? description;

  const RecipeStep({
    required this.stepNumber,
    required this.title,
    this.description,
  });
}

enum RecipeCategory {
  breakfast,
  midMorning,
  lunch,
  eveningSnack,
  dinner,
  bedtime,
}

extension RecipeCategoryExt on RecipeCategory {
  String get label {
    switch (this) {
      case RecipeCategory.breakfast:    return 'Breakfast';
      case RecipeCategory.midMorning:   return 'Mid Morning';
      case RecipeCategory.lunch:        return 'Lunch';
      case RecipeCategory.eveningSnack: return 'Evening Snack';
      case RecipeCategory.dinner:       return 'Dinner';
      case RecipeCategory.bedtime:      return 'Bedtime';
    }
  }

  String get emoji {
    switch (this) {
      case RecipeCategory.breakfast:    return '🌅';
      case RecipeCategory.midMorning:   return '🍎';
      case RecipeCategory.lunch:        return '☀️';
      case RecipeCategory.eveningSnack: return '🌤️';
      case RecipeCategory.dinner:       return '🌙';
      case RecipeCategory.bedtime:      return '🍼';
    }
  }
}

class RecipeModel {
  final String id;
  final String name;
  final String description;
  final String imageUrl;
  final int cookTimeMinutes;
  final int calories;
  final String tag; // e.g. "Summer special", "High Protein"
  final String benefit; // short benefit text
  final List<String> ageGroups; // e.g. ['6-8 Months', '9-12 Months']
  final RecipeCategory category;
  final List<RecipeIngredient> ingredients;
  final List<RecipeStep> steps;
  final String howToServe;
  final bool isBookmarked;

  const RecipeModel({
    required this.id,
    required this.name,
    required this.description,
    required this.imageUrl,
    required this.cookTimeMinutes,
    required this.calories,
    required this.tag,
    required this.benefit,
    required this.ageGroups,
    required this.category,
    required this.ingredients,
    required this.steps,
    required this.howToServe,
    this.isBookmarked = false,
  });

  bool get isVeg {
    final lowerName = name.toLowerCase();
    final lowerDesc = description.toLowerCase();
    final nonVegKeywords = ['egg', 'chicken', 'fish', 'meat', 'mutton', 'prawn', 'shrimp', 'salmon', 'tuna', 'non-veg'];
    
    for (final kw in nonVegKeywords) {
      if (lowerName.contains(kw) || lowerDesc.contains(kw)) {
        if (lowerName.contains('eggplant') || lowerDesc.contains('eggplant')) {
          continue;
        }
        if (lowerName.contains('eggless') || lowerDesc.contains('eggless')) {
          continue;
        }
        return false;
      }
    }
    
    for (final ing in ingredients) {
      final lowerIng = ing.name.toLowerCase();
      for (final kw in nonVegKeywords) {
        if (lowerIng.contains(kw)) {
          if (lowerIng.contains('eggplant') || lowerIng.contains('eggless')) {
            continue;
          }
          return false;
        }
      }
    }
    return true;
  }

  RecipeModel copyWith({bool? isBookmarked}) {
    return RecipeModel(
      id: id,
      name: name,
      description: description,
      imageUrl: imageUrl,
      cookTimeMinutes: cookTimeMinutes,
      calories: calories,
      tag: tag,
      benefit: benefit,
      ageGroups: ageGroups,
      category: category,
      ingredients: ingredients,
      steps: steps,
      howToServe: howToServe,
      isBookmarked: isBookmarked ?? this.isBookmarked,
    );
  }

  factory RecipeModel.fromMap(Map<String, dynamic> map) {
    final rawIngredients = map['ingredients'] as List<dynamic>? ?? [];
    final ingredientsList = rawIngredients.map((i) {
      final m = Map<String, dynamic>.from(i as Map);
      return RecipeIngredient(
        name: m['name'] as String? ?? '',
        quantity: m['quantity'] as String? ?? '',
        imageUrl: m['imageUrl'] as String?,
      );
    }).toList();

    final rawSteps = map['steps'] as List<dynamic>? ?? [];
    final stepsList = rawSteps.map((s) {
      final m = Map<String, dynamic>.from(s as Map);
      return RecipeStep(
        stepNumber: (m['stepNumber'] as num?)?.toInt() ?? 1,
        title: m['title'] as String? ?? '',
        description: m['description'] as String?,
      );
    }).toList();

    final catStr = map['category'] as String? ?? 'breakfast';
    RecipeCategory category;
    switch (catStr) {
      case 'midMorning': category = RecipeCategory.midMorning; break;
      case 'lunch': category = RecipeCategory.lunch; break;
      case 'eveningSnack': category = RecipeCategory.eveningSnack; break;
      case 'dinner': category = RecipeCategory.dinner; break;
      case 'bedtime': category = RecipeCategory.bedtime; break;
      default: category = RecipeCategory.breakfast; break;
    }

    return RecipeModel(
      id: map['id'] as String,
      name: map['name'] as String? ?? '',
      description: map['description'] as String? ?? '',
      imageUrl: map['image_url'] as String? ?? '',
      cookTimeMinutes: (map['cook_time_minutes'] as num?)?.toInt() ?? 0,
      calories: (map['calories'] as num?)?.toInt() ?? 0,
      tag: map['tag'] as String? ?? '',
      benefit: map['benefit'] as String? ?? '',
      ageGroups: List<String>.from(map['age_groups'] as List<dynamic>? ?? []),
      category: category,
      ingredients: ingredientsList,
      steps: stepsList,
      howToServe: map['how_to_serve'] as String? ?? '',
    );
  }
}

